#!/usr/bin/env python3
"""Generate config option artifacts from crates/mare-config/preset/config_api.lua.

Targets:
  crates/mare-config/src/options_gen.rs          CORE_OPTIONS
  crates/mare-plugin/preset/types/mare/config.lua  mare.SetupOpts LuaLS class

Usage:
  scripts/gen_options.py           # write generated files
  scripts/gen_options.py --check   # exit 1 if any generated file is stale
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import plugin_options

ROOT = Path(__file__).resolve().parent.parent
OPTIONS_LUA = ROOT / "crates/mare-config/preset/config_api.lua"
RUST_OUT = ROOT / "crates/mare-config/src/options_gen.rs"
LUALS_FILE = ROOT / "crates/mare-plugin/preset/types/mare/config.lua"

BEGIN_MARKER = "-- BEGIN GENERATED SetupOpts (scripts/gen_options.py)"
END_MARKER = "-- END GENERATED SetupOpts"

LUA_DUMP = r"""
local mare = {}
local chunk = assert(loadfile(arg[1]))
pcall(chunk, mare, {})
local names = {}
for name in pairs(mare.options) do names[#names + 1] = name end
table.sort(names)
for _, name in ipairs(names) do
  local o = mare.options[name]
  local luals = o.luals_type
  if not luals then
    luals = type(o.type) == "table" and table.concat(o.type, "|") or tostring(o.type)
  end
  local desc = (o.desc or ""):gsub("[\t\r\n]+", " "):gsub("^%s+", ""):gsub("%s+$", "")
  io.write(table.concat({ name, luals, desc }, "\t"), "\n")
end
"""


def load_options(lua: str) -> list[tuple[str, str, str]]:
    dump = subprocess.run(
        [lua, "-e", LUA_DUMP.replace("arg[1]", repr(str(OPTIONS_LUA)))],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    rows = []
    for line in dump.splitlines():
        name, luals, desc = line.split("\t")
        rows.append((name, luals, desc))
    return rows


def render_rust(rows: list[tuple[str, str, str]]) -> str:
    core_items = "\n".join(f'    "{name}",' for name, _, _ in rows)

    return (
        "// @generated by scripts/gen_options.py from crates/mare-config/preset/config_api.lua.\n"
        "// Do not edit by hand.\n"
        "\n"
        "/// Every registered core option (the `mare.options` registry in [`crate::CONFIG_API`];\n"
        "/// tests keep them in sync), for the `MARE_<NAME>` environment layer.\n"
        "pub const CORE_OPTIONS: &[&str] = &[\n"
        f"{core_items}\n"
        "];\n"
    )


def render_setup_opts(rows: list[tuple[str, str, str]]) -> str:
    lines = [BEGIN_MARKER, "---@class mare.SetupOpts"]
    for name, luals, desc in rows:
        lines.append(f"---@field {name}? {luals} {desc}" if desc else f"---@field {name}? {luals}")
    lines.append(END_MARKER)
    return "\n".join(lines)


def update_luals(existing: str, block: str) -> str:
    start = existing.index(BEGIN_MARKER)
    end = existing.index(END_MARKER) + len(END_MARKER)
    return existing[:start] + block + existing[end:]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--lua", default="lua", help="Lua 5.4+ interpreter")
    ap.add_argument("--check", action="store_true", help="exit 1 if generated files are stale")
    args = ap.parse_args()

    rows = load_options(args.lua)
    rust_content = render_rust(rows)
    luals_existing = LUALS_FILE.read_text(encoding="utf-8")
    luals_content = update_luals(luals_existing, render_setup_opts(rows))
    plugin_luals = plugin_options.render_plugin_luals(plugin_options.load_plugin_schemas(args.lua))

    targets = [
        (RUST_OUT, rust_content),
        (LUALS_FILE, luals_content),
        (plugin_options.PLUGIN_LUALS_OUT, plugin_luals),
    ]
    stale = []
    for path, content in targets:
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(content, encoding="utf-8")
    errs = plugin_options.check_declared_keys(ROOT, args.lua)
    if stale:
        print("stale generated option files (run python3 scripts/gen_options.py):", *stale, sep="\n  ", file=sys.stderr)
    if errs:
        print("undeclared plugin config key reads:", *errs, sep="\n  ", file=sys.stderr)
    return 1 if (stale or errs) else 0


if __name__ == "__main__":
    sys.exit(main())
