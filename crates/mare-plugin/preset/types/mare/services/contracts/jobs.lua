---@meta _
-- The `jobs` service contract. Part of the built-in contracts (see contracts/schema.lua).
local S = ...
local object, integer, string, boolean, page_of = S.object, S.integer, S.string, S.boolean, S.page_of
local job = object({
	job_id = string,
	kind = string,
	description = string,
	label = string,
	owner = string,
	status = { type = "string", enum = { "running", "completed", "failed", "cancelled", "interrupted" } },
	exit_code = integer,
	exit_signal = integer,
	background = boolean,
	started_at_ms = integer,
	ended_at_ms = integer,
	kill_requested = boolean,
	kill_reason = string,
	stop_unconfirmed = boolean,
	over_limit = integer,
}, { "job_id", "kind", "owner", "status", "started_at_ms" }, true)
return {
	["jobs"] = {
		doc = "Background jobs started by bash or tracked by plugins.",
		errors = {
			unknown_job = { doc = "no job with that job_id" },
		},
		methods = {
			list = {
				doc = "Background jobs in start order, optionally filtered by owner (with optional cursor pagination).",
				expose = "both",
				access = "peer",
				scope = "session",
				params = object(S.merged(S.page_params_props, { owner = string })),
				order = { "..." },
				result = page_of(job),
			},
			read = {
				doc = "Non-consumingly read job output starting at byte `offset`, with a trailing [status: ...] line.",
				expose = "both",
				access = "peer",
				scope = "session",
				params = object({
					job_id = string,
					offset = { type = "integer", minimum = 0 },
					max_bytes = { type = "integer", minimum = 1 },
				}, { "job_id" }),
				order = { "job_id", "..." },
				result = object({
					text = string,
					dropped = integer,
					next_offset = integer,
					done = boolean,
				}, { "text" }),
				errors = { "unknown_job" },
			},
			background = {
				doc = "Mark a job as backgrounded so completion emits a notification.",
				expose = "both",
				access = "peer",
				scope = "session",
				params = object({ job_id = string }, { "job_id" }),
				order = { "job_id" },
				result = object({}),
				errors = { "unknown_job" },
			},
			cancel = {
				doc = "Request a running job to stop (SIGTERM, then SIGKILL after kill_grace_ms).",
				expose = "both",
				access = "peer",
				scope = "session",
				params = object({ job_id = string, reason = string, silent = boolean }, { "job_id" }),
				order = { "job_id", "reason", "..." },
				result = object({}),
				errors = { "unknown_job" },
			},
			start = {
				doc = "Start and track a background process job.",
				lua_unchecked = true,
				params = object({
					kind = string,
					description = string,
					cmd = string,
					args = { type = "array", items = string },
					cwd = string,
					env = { type = "object", additionalProperties = true },
					spill = string,
					sandbox = { type = "object", additionalProperties = true },
					owner = string,
					background = boolean,
				}, { "cmd" }, true),
				order = { "..." },
				result = { oneOf = { job, { type = "null" } } },
				lua_result = { "mare.JobInfo|nil", "string?" },
			},
			track = {
				doc = "Track an external handle implementing the `mare.Job` interface (sub-agents, terminals) as a job.",
				lua_unchecked = true,
				params = object({
					kind = string,
					description = string,
					owner = string,
					background = boolean,
				}, { "kind" }, true),
				lua = { handle = "table" },
				order = { "..." },
				result = job,
				lua_result = "mare.JobInfo",
			},
			get = {
				doc = "Look up a tracked job by id (optionally scoped to `owner`), or nil.",
				lua_unchecked = true,
				params = object({ job_id = string, owner = string }, { "job_id" }),
				order = { "job_id", "owner" },
				result = { oneOf = { job, { type = "null" } } },
				lua_result = "mare.JobInfo|nil",
			},
			write = {
				doc = "Write stdin data to a running job (optionally closing stdin with `eof = true`).",
				lua_unchecked = true,
				params = object({ job_id = string, data = string, eof = boolean }, { "job_id" }),
				order = { "job_id", "data", "..." },
				result = boolean,
				lua_result = { "boolean", "string?" },
			},
		},
		events = {
			["changed"] = {
				doc = "Background job state changed.",
				mode = "emit",
				expose = "both",
				delivery = "lossy",
				ignorable = false,
				retain = "last",
				data = object({ job = job, truncated = boolean }, { "job" }),
				example = {
					job = {
						job_id = "j-1",
						kind = "bash",
						owner = "bash",
						status = "running",
						started_at_ms = 1700000000000,
					},
				},
			},
			["internal-changed"] = {
				doc = "Internal job state update carrying the live in-process job handle.",
				mode = "emit",
				expose = "process",
				retain = "last",
				data = object({ job = job }, { "job" }),
			},
		},
	},
}
