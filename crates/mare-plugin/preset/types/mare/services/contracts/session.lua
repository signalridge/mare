local function search_params(require_session_id)
	local props = S.merged(S.page_params_props, {
		query = string,
		title_query = string,
		sort_key = { type = "string", enum = { "relevance", "created_at_ms", "updated_at_ms" } },
		sort_direction = { type = "string", enum = { "asc", "desc" } },
		filters = history_filters,
		event_filters = history_event_filters,
		step_bound = boolean,
	})
	if require_session_id then
		props.session_id = string
		return object(props, { "session_id" })
	end
	return object(props)
end
