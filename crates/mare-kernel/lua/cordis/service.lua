local proto = require("cordis.proto")
local classlib = require("cordis.class")
local symbols = require("cordis.symbols")
local S = symbols.symbols
local trace = require("cordis.trace")
local reflect = require("cordis.reflect")

local Service = classlib.class("Service")

Service.init = S.init
Service.check = S.check
Service.invoke = S.invoke
Service.metadata = S.metadata
Service.extend = S.extend
Service.tracker = S.tracker
Service.mergeIntercept = S.mergeIntercept
Service.resolveIntercept = S.resolveIntercept
Service.filter = S.filter

function Service:constructor(ctx, name)
  if name == nil then
    name = self.provide
  end
  local tracker = { associate = name, property = "ctx" }
  -- a service with `[Service.invoke]` is callable through the
  -- class `__call` metamethod; no replacement object is needed
  rawset(self, "ctx", ctx)
  rawset(self, "name", name)
  rawset(self, S.tracker, tracker)
  local check = self[S.check]
  ctx.reflect:provide(name, self, check and function(value)
    return check(value)
  end)
end

-- `self(...)`: invoke through a traceable proxy (createCallable)
function Service.__call(self, ...)
  local proxy = trace.createTraceable(proto.get(self, "ctx", self), self, proto.get(self, S.tracker, self))
  return proxy(...)
end

Service[S.filter] = function(self, ctx)
  return ctx[S.isolate][self.name] == self.ctx[S.isolate][self.name]
end

Service[S.extend] = function(self, props)
  local derived = proto.create(self)
  if props then
    proto.assign(derived, props)
  end
  return derived
end

Service[S.mergeIntercept] = function(_, ...)
  local result = {}
  for i = 1, select("#", ...) do
    local v = select(i, ...)
    if v ~= nil and v ~= symbols.null then
      if proto.is(v) then
        for _, k in ipairs(proto.keys(v)) do
          result[k] = v[k]
        end
      elseif type(v) == "table" then
        for k, x in pairs(v) do
          result[k] = x
        end
      end
    end
  end
  return result
end

Service[S.resolveIntercept] = function(self)
  local values = {}
  local name = self.name
  local intercept = self.ctx[S.intercept]
  while intercept ~= nil and proto.has(intercept, name) do
    if proto.hasOwn(intercept, name) then
      table.insert(values, 1, proto.getOwn(intercept, name))
    end
    intercept = proto.getPrototypeOf(intercept)
  end
  local located = reflect.locate(self[S.caller] or self.ctx, name)
  local value = located and located.fiber and located.fiber.inject[name]
  if not symbols.isNullable(value) then
    table.insert(values, 1, value)
  end
  local merge = self[S.mergeIntercept] or Service[S.mergeIntercept]
  return merge(self, table.unpack(values))
end

-- `instanceof Service` (Symbol.hasInstance) is `Service.is(x)`, generated by
-- cordis.class; it sees through traceable proxies and derived objects.

return Service
